    inv = [el4.index(tuple(np.argsort(g))) for g in el4]

    def gm(*gs):
        r = 0
        for g in gs:
            r = int(mul4[r, g])
        return r

    a = sorted({e, xi, yi, gm(inv[xi], yi, xi)})
    b = sorted({e, xi, yi, gm(yi, xi)})
    HX, HZ = build_2bga(mul4, a, b)
    print(f"non-abelian A4 2BGA: n={HX.shape[1]} k={compute_k(HX, HZ)} "
          f"css={verify_css(HX, HZ)} d<={distance_rand(HX, HZ, trials=1500)} "
          f"(odd k is unreachable by abelian BB)")
