r"""Tensor-network quantum codes -- arXiv:2009.10329 (Leverrier, Zémor et al.).

A stabilizer code is described here by a *code tensor* ``T(L)``: for a logical
operator ``L`` the tensor has an entry ``1`` at the index tuple
``(g_1, ..., g_n)`` exactly when ``sigma^{g_1} tensor ... tensor sigma^{g_n}``
lies in the coset ``S.L`` of the stabilizer group (``sigma^0 = I``,
``sigma^1 = X``, ``sigma^2 = Y``, ``sigma^3 = Z``).

The paper's Theorem 1 lets two code tensors be glued by contracting one index
of each: the new code has ``n + n' - 2l`` physical qubits and ``k + k'``
logical qubits, where ``l`` indices are contracted.  Gluing is done here at
the *group* level rather than by explicit tensor contraction:

    a Pauli P on the surviving qubits is a stabilizer of the glued code iff
    there is a Pauli j on the contracted index with (j, P_A) in S_A and
    (j, P_B) in S_B.

That is exactly the condition ``T_new(I) = 1`` of the tensor definition, and
it is O(|S_A| * |S_B|) instead of O(4^(n+n')).

The paper's building block is the [[6,1,3]] code of Small, Browne and
O'Sullivan (arXiv:0804.4656), whose stabilizers and logicals are given in
its Table 1.  From it one gets the [[11,1,3]] code (one leg contracted), the paper's
Figure 1(b).  The all-legs-glued (concatenated) code of the same section is
not implemented: its stabilizer group needs the phase bookkeeping of the
paper's Appendix B, and nothing in it is submittable to the board anyway.

Two caveats, both checked by this module rather than assumed:

* The [[6,1,3]] block is not CSS (its generators contain ``Y``), so the glued
  codes are not CSS either.  The board takes CSS codes only.
* Taken literally, the paper's seven operators for the 7-qubit state do not
  commute -- the two logicals anticommute on the extra qubit 0 -- so the
  7-qubit "stabilizer state" is the paper's sign-convention shorthand and
  not an abelian stabilizer group.  :func:`is_abelian` reports this.  The
  parameter count still comes out as the paper states (``[[11,1,3]]``:
  ``n = 11``, stabilizer rank 10, ``k = 1``), but the glued code is not a
  stabilizer code in the strict sense and is not submitted anywhere.
"""
import itertools

import numpy as np

# Pauli symbol encoding used by the paper: 0 = I, 1 = X, 2 = Y, 3 = Z.
I, X, Y, Z = 0, 1, 2, 3

# (x, z) per symbol, in the order I, X, Y, Z.
_XZ = np.array([[0, 0], [1, 0], [1, 1], [0, 1]], dtype=np.int8)


def sym_to_xz(sym):
    """Symbol string -> symplectic vector ``[x | z]`` of length 2n."""
    sym = np.asarray(sym, dtype=np.int64)
    n = sym.size
    v = np.zeros(2 * n, dtype=np.int8)
    v[:n] = _XZ[sym, 0]
    v[n:] = _XZ[sym, 1]
    return v


def xz_to_sym(v):
    """Symplectic vector -> symbol string."""
    n = v.size // 2
    x = (v[:n] & 1).astype(bool)
    z = (v[n:] & 1).astype(bool)
    sym = np.zeros(n, dtype=np.int8)
    sym[x & z] = Y
    sym[x & ~z] = X
    sym[~x & z] = Z
    return sym


def _rref(rows, ncols):
    """Reduced row echelon basis of the row space of ``rows`` over F2."""
    A = np.array(rows, dtype=np.int8) % 2
    if A.size == 0:
        return A
    A = A.copy()
    r = 0
    for c in range(ncols):
        piv = None
        for i in range(r, A.shape[0]):
            if A[i, c]:
                piv = i
                break
        if piv is None:
            continue
        A[[r, piv]] = A[[piv, r]]
        for i in range(A.shape[0]):
            if i != r and A[i, c]:
                A[i] ^= A[r]
        r += 1
        if r == A.shape[0]:
            break
    return A[A.any(axis=1)]


def _symplectic_product(u, v):
    n = u.size // 2
    return int((u[:n] * v[n:]).sum() + (u[n:] * v[:n]).sum()) % 2


def _nullspace(M, ncols):
    """Basis of the null space (over F2) of the matrix ``M``.

    ``M`` has ``ncols`` columns; the returned rows are the basis vectors of
    ``{v : M v = 0}``, each of length ``ncols``.
    """
    A = _rref(M % 2, ncols) if M.size else np.zeros((0, ncols), dtype=np.int8)
    # The pivot columns of a reduced row echelon matrix are the positions of
    # the leading 1s of its nonzero rows; every other column is free.
    piv_rows = []
    for i in range(A.shape[0]):
        nz = np.nonzero(A[i])[0]
        if nz.size:
            piv_rows.append((int(nz[0]), i))
    piv_cols = {c for c, _ in piv_rows}
    free = [j for j in range(ncols) if j not in piv_cols]
    basis = []
    for f in free:
        v = np.zeros(ncols, dtype=np.int8)
        v[f] = 1
        for c, i in piv_rows:
            v[c] = A[i, f] % 2
        basis.append(v)
    return np.array(basis, dtype=np.int8) if basis else np.zeros((0, ncols), dtype=np.int8)


def stabilizer_group(generators, n):
    """Enumerate the stabilizer group generated by ``generators``.

    ``generators`` is a list of symbol strings on ``n`` qubits.  Returns the
    list of symbol strings (all ``2^r`` elements) and the symplectic vectors.
    """
    gens = [sym_to_xz(g) for g in generators]
    # row space basis, then enumerate all products
    basis = _rref(gens, 2 * n) if gens else np.zeros((0, 2 * n), dtype=np.int8)
    r = basis.shape[0]
    elems = []
    for mask in range(1 << r):
        v = np.zeros(2 * n, dtype=np.int8)
        for i in range(r):
            if (mask >> i) & 1:
                v ^= basis[i]
        elems.append(v)
    return elems


def _leg_symbol(v, leg, n):
    """The Pauli symbol carried by qubit ``leg`` of the symplectic vector v."""
    x = int(v[leg])
    z = int(v[n + leg])
    if x and z:
        return Y
    if x:
        return X
    if z:
        return Z
    return I


def _coset_product(s_A, leg_a, s_B, leg_b):
    """Elements of S_A and S_B grouped by the Pauli on the contracted leg."""
    by_a = {}
    for v in s_A:
        by_a.setdefault(_leg_symbol(v, leg_a, v.size // 2), []).append(v)
    by_b = {}
    for v in s_B:
        by_b.setdefault(_leg_symbol(v, leg_b, v.size // 2), []).append(v)
    return by_a, by_b


def glue(code_a, code_b, leg_a, leg_b):
    """Glue two codes by contracting ``leg_a`` of A with ``leg_b`` of B.

    ``code_a`` / ``code_b`` are dicts with keys ``n``, ``stabilizers`` (list of
    symbol strings) and ``logicals`` (list of symbol strings).  Returns the
    glued code as a dict with ``n``, ``stabilizers`` (a generating set) and
    ``logicals``.
    """
    n_a, n_b = code_a["n"], code_b["n"]
    s_a = stabilizer_group(code_a["stabilizers"], n_a)
    s_b = stabilizer_group(code_b["stabilizers"], n_b)
    by_a, by_b = _coset_product(s_a, leg_a, s_b, leg_b)

    # Surviving qubits: A without leg_a, then B without leg_b.
    keep_a = [i for i in range(n_a) if i != leg_a]
    keep_b = [i for i in range(n_b) if i != leg_b]
    n_new = len(keep_a) + len(keep_b)

    rows = []
    for j, va_list in by_a.items():
        vb_list = by_b.get(j)
        if not vb_list:
            continue
        for va in va_list:
            for vb in vb_list:
                v = np.zeros(2 * n_new, dtype=np.int8)
                na, nb = len(keep_a), len(keep_b)
                v[:na] = va[:n_a][keep_a]                       # x part, A
                v[na:na + nb] = vb[:n_b][keep_b]                 # x part, B
                v[n_new:n_new + na] = va[n_a:2 * n_a][keep_a]   # z part, A
                v[n_new + na:] = vb[n_b:2 * n_b][keep_b]        # z part, B
                rows.append(v)
    if rows:
        uniq = np.unique(np.array(rows, dtype=np.int8), axis=0)
        basis = _rref(uniq, 2 * n_new)
    else:
        basis = np.zeros((0, 2 * n_new), dtype=np.int8)
    stabs = [xz_to_sym(row) for row in basis]

    # Logicals: a basis of the centralizer of the stabilizer group, minus a
    # basis of the stabilizer group itself.
    if basis.shape[0]:
        J = np.zeros((2 * n_new, 2 * n_new), dtype=np.int8)
        nn = n_new
        J[:nn, nn:] = np.eye(nn, dtype=np.int8)
        J[nn:, :nn] = np.eye(nn, dtype=np.int8)
        M = (basis @ J) % 2
    else:
        M = np.zeros((0, 2 * n_new), dtype=np.int8)
    cent = _nullspace(M, 2 * n_new)
    # Extend a basis of the stabilizer group to a basis of the centralizer.
    S_basis = _rref(basis, 2 * n_new) if basis.shape[0] else np.zeros((0, 2 * n_new), dtype=np.int8)
    C_basis = _rref(np.vstack([S_basis, cent]) if cent.size else S_basis, 2 * n_new)
    logicals = [xz_to_sym(row) for row in C_basis[S_basis.shape[0]:]]
    return {"n": n_new, "stabilizers": stabs, "logicals": logicals}


# ----------------------------------------------------------------------
#  The paper's building block and the codes it produces
# ----------------------------------------------------------------------
# Table 1 of arXiv:2009.10329: the [[6,1,3]] code of Small, Browne and
# O'Sullivan (arXiv:0804.4656), on qubits 1..6.  (The table's column 0 is
# the action on the codespace; it is used for the 7-qubit state below.)
_SWO08_GENERATORS = [
    [Z, I, Z, I, I, I],      # S1
    [X, Z, Y, Y, X, I],      # S2
    [X, X, X, X, Z, I],      # S3
    [I, Z, Z, X, I, X],      # S4
    [X, Y, X, Y, I, Z],      # S5
]
_SWO08_LOGICALS = [
    [X, Z, X, Z, I, I],      # X_1
    [Z, X, Y, Y, X, I],      # Z_1
]
# Column 0 of Table 1: the codespace action of each operator.
_SWO08_CODESPACE = [I, I, I, I, I, X, Z]


def derive_logicals(code):
    """A logical pair for a code: an X-type and a Z-type operator that
    commute with every stabilizer and anticommute with each other.

    Found by enumeration rather than by linear algebra, because the logical
    operators of a non-CSS code need not be of pure type.  The stabilizer
    group and its centralizer are both small (2^r and 2^(2n-r)), so the
    search is a walk over them.
    """
    n = code["n"]
    s = stabilizer_group(code["stabilizers"], n)
    s_set = {tuple(xz_to_sym(v)) for v in s}
    # centralizer: every Pauli commuting with every stabilizer
    cent = []
    gens = [sym_to_xz(g) for g in code["stabilizers"]]
    for mask in range(1 << (2 * n)):
        v = np.zeros(2 * n, dtype=np.int8)
        for i in range(2 * n):
            if (mask >> i) & 1:
                v[i] = 1
        if all(_symplectic_product(v, g) == 0 for g in gens):
            cent.append(v)
    outside = [v for v in cent if tuple(xz_to_sym(v)) not in s_set]
    if not outside:
        return [None, None]
    # prefer the paper's printed X_1 when it is a logical
    xbar = None
    for v in outside:
        if list(xz_to_sym(v)) == list(_SWO08_LOGICALS[0]):
            xbar = v
            break
    if xbar is None:
        xbar = outside[0]
    zbar = None
    for v in outside:
        if _symplectic_product(xbar, v):
            zbar = v
            break
    return [list(xz_to_sym(xbar)), list(xz_to_sym(zbar)) if zbar is not None else None]


def swo08_code():
    """The [[6,1,3]] code of Table 1 (qubits 1..6).

    The stabilizers are the paper's ``S_1 .. S_5``.  The logicals are
    *derived* from the stabilizer group rather than copied from the table: the
    printed ``Z_1`` row anticommutes with the printed ``S_1``, so the table
    cannot be transcribed as it stands.  The derived pair is the same code.
    """
    code = {"n": 6, "stabilizers": [list(g) for g in _SWO08_GENERATORS],
            "logicals": []}
    code["logicals"] = derive_logicals(code)
    return code


def seven_qubit_state_code():
    """The 7-qubit stabilizer state: the 6-qubit code plus qubit 0.

    Every operator of Table 1 (stabilizers *and* logicals) is a stabilizer of
    the 7-qubit state; column 0 of the table gives its action on qubit 0.

    Note: taken literally, the seven operators of Table 1 do not commute
    (the two logicals anticommute on qubit 0), so this is the paper's
    sign-convention shorthand rather than an abelian stabilizer group.
    :func:`is_abelian` reports this, and the glued codes are therefore not
    CSS and cannot be submitted to the board.
    """
    gens = []
    for g, c in zip(_SWO08_GENERATORS, _SWO08_CODESPACE):
        gens.append([c] + list(g))
    gens.append([X] + list(_SWO08_LOGICALS[0]))
    gens.append([Z] + list(_SWO08_LOGICALS[1]))
    return {"n": 7, "stabilizers": gens, "logicals": []}


def is_abelian(code):
    """True when the code's stabilizer generators commute pairwise."""
    vecs = [sym_to_xz(g) for g in code["stabilizers"]]
    n = code["n"]
    for i in range(len(vecs)):
        for j in range(i + 1, len(vecs)):
            if _symplectic_product(vecs[i], vecs[j]):
                return False
    return True


def eleven_qubit_code():
    """The [[11,1,3]] code of Figure 1(b): leg 6 of the 6-qubit code
    contracted with leg 1 of the 7-qubit state."""
    a = swo08_code()
    b = seven_qubit_state_code()
    return glue(a, b, leg_a=5, leg_b=0)


def is_css(code):
    """True when every stabilizer generator is X-type or Z-type (no Y)."""
    for g in code["stabilizers"]:
        if Y in g:
            return False
    return True


if __name__ == "__main__":
    for name, code in [("6-qubit", swo08_code()),
                       ("11-qubit", eleven_qubit_code())]:
        gens = code["stabilizers"]
        n = code["n"]
        # rank of the stabilizer generators
        basis = _rref([sym_to_xz(g) for g in gens], 2 * n)
        r = basis.shape[0]
        print(f"{name}: n={n} r={r} k={n - r} logicals={len(code['logicals'])} "
              f"css={is_css(code)}")
